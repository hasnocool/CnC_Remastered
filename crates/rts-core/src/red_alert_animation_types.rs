/// Safe counterpart of AnimTypeClass::As_Reference.
pub fn as_reference(id: AnimationTypeId) -> Option<&'static AnimationTypeRecord> {
    ANIMATION_TYPES.get(id.index())
}

/// Resolve an upstream enum symbol without relying on the C++ enum headers.
pub fn id_for_symbol(symbol: &str) -> Option<AnimationTypeId> {
    ANIMATION_TYPES.iter().find(|record| record.type_symbol == symbol).map(|record| record.id)
}

/// Port of Anim_Name: ANIM_NONE maps to the empty string.
pub fn animation_name(id: Option<AnimationTypeId>) -> &'static str {
    id.and_then(as_reference).map_or("", |record| record.ini_name)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AssetLookupPolicy {
    /// Debug C++ builds try a loose RawFileClass first, then fall back to MFCD.
    LooseFileThenArchive,
    /// Release C++ builds and theater changes use MFCD directly.
    ArchiveOnly,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AnimationAssetRequest {
    pub animation: AnimationTypeId,
    pub filename: String,
    pub lookup: AssetLookupPolicy,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ImageAlias {
    pub source: AnimationTypeId,
    pub destination: AnimationTypeId,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TheaterAssetPlan {
    pub theater_key: String,
    pub requests: Vec<AnimationAssetRequest>,
    /// ADATA.CPP copies Beacon.ImageData to BeaconVirtual.ImageData.
    pub beacon_virtual_alias: ImageAlias,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AssetPlanError {
    OneTimeInitializationAlreadyPlanned,
}

/// Plans the original one-time and theater-specific asset requests. It does no
/// file I/O; callers can dispatch requests through an asynchronous asset
/// service and attach the resolved image handles to the corresponding IDs.
#[derive(Debug, Default)]
pub struct AnimationAssetPlanner {
    one_time_planned: bool,
    last_theater: Option<String>,
}

impl AnimationAssetPlanner {
    /// Port of AnimTypeClass::One_Time. Theater-specific records are skipped.
    /// Debug builds prefer loose files; release builds use the archive.
    pub fn plan_one_time_loads(
        &mut self,
        debug_build: bool,
    ) -> Result<Vec<AnimationAssetRequest>, AssetPlanError> {
        if self.one_time_planned {
            return Err(AssetPlanError::OneTimeInitializationAlreadyPlanned);
        }
        self.one_time_planned = true;
        let lookup = if debug_build {
            AssetLookupPolicy::LooseFileThenArchive
        } else {
            AssetLookupPolicy::ArchiveOnly
        };
        Ok(ANIMATION_TYPES.iter().filter(|record| !record.is_theater).map(|record| {
            AnimationAssetRequest {
                animation: record.id,
                filename: format!("{}.SHP", record.ini_name),
                lookup,
            }
        }).collect())
    }

    /// Port of AnimTypeClass::Init. A repeated theater key is a no-op.
    /// Suffix is exactly the source-provided Theaters[theater].Suffix text.
    pub fn plan_theater_change(
        &mut self,
        theater_key: &str,
        suffix: &str,
    ) -> Option<TheaterAssetPlan> {
        if self.last_theater.as_deref() == Some(theater_key) {
            return None;
        }
        self.last_theater = Some(theater_key.to_owned());
        let requests = ANIMATION_TYPES.iter().filter(|record| record.is_theater).map(|record| {
            AnimationAssetRequest {
                animation: record.id,
                filename: format!("{}{}", record.ini_name, suffix),
                lookup: AssetLookupPolicy::ArchiveOnly,
            }
        }).collect();
        Some(TheaterAssetPlan {
            theater_key: theater_key.to_owned(),
            requests,
            beacon_virtual_alias: ImageAlias {
                source: AnimationTypeId::new(80),      // ANIM_BEACON
                destination: AnimationTypeId::new(88), // ANIM_BEACON_VIRTUAL
            },
        })
    }
}

