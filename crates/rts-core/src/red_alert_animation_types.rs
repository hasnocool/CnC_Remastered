//! Source-derived Red Alert animation type registry from REDALERT/ADATA.CPP.
//!
//! Upstream baseline: electronicarts/CnC_Remastered_Collection
//! commit f1f0d42bc2dcd06d5d1df943c6150ab34bf307ae.
//!
//! The 89 records preserve the exact AnimTypeClass::Init_Heap allocation
//! order. The original source intentionally allocates in enum order because
//! each heap block index doubles as the animation type number. Asset I/O is
//! represented as deterministic requests so a platform asset service can
//! perform file/archive lookup without coupling this crate to Win32 I/O.

use crate::fixed16::Fixed16;

pub const ANIMATION_COUNT: usize = 89;
pub const ANIMATION_RTTI: &str = "RTTI_ANIMTYPE";
pub const ANIMATION_TEXT_ID: &str = "TXT_NONE";

/// Shared ObjectTypeClass constructor flags passed by ADATA.CPP.
pub const OBJECT_TYPE_FLAGS: [bool; 7] = [true, true, false, false, true, true, false];

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct AnimationTypeId(u8);

impl AnimationTypeId {
    pub const fn new(index: u8) -> Self { Self(index) }
    pub const fn index(self) -> usize { self.0 as usize }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AnimationTypeRecord {
    pub id: AnimationTypeId,
    pub source_static_name: &'static str,
    pub type_symbol: &'static str,
    pub ini_name: &'static str,
    pub size: i32,
    pub biggest: i32,
    pub is_theater: bool,
    pub normalized: bool,
    pub white_trans: bool,
    pub scorcher: bool,
    pub crater_forming: bool,
    pub sticky: bool,
    pub ground_layer: bool,
    pub translucent: bool,
    pub flame_thrower: bool,
    pub damage: Fixed16,
    pub delay: i32,
    pub start: i32,
    pub loop_start: i32,
    pub loop_end: i32,
    pub stages: i32,
    pub loops: i32,
    pub sound_symbol: &'static str,
    pub chain_to_symbol: &'static str,
    pub virtual_stages: i32,
    pub virtual_scale: i32,
    pub virtual_name: Option<&'static str>,
    pub virtual_animation_symbol: &'static str,
}

impl AnimationTypeRecord {
    /// ADATA.CPP overrides ObjectTypeClass::Create_And_Place to always fail.
    pub const fn can_create_and_place(&self) -> bool { false }

    /// ADATA.CPP overrides ObjectTypeClass::Create_One_Of to always return null.
    pub const fn create_one_of(&self) -> Option<()> { None }
}

