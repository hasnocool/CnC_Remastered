#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct AdpcmState {
    /// Current table offset, always a multiple of 16 after a decoded nibble.
    pub sample_index: usize,
    /// Signed 16-bit predictor carried as a source-compatible 32-bit integer.
    pub predicted: i32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AdpcmError {
    InvalidSampleIndex(usize),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AdpcmBlock {
    pub samples: Vec<i16>,
}

impl AdpcmBlock {
    /// Equivalent to the source function's return value: two 16-bit samples
    /// are emitted for each compressed input byte.
    pub fn decompressed_size_bytes(&self) -> usize {
        self.samples.len().saturating_mul(2)
    }
}

fn decode_nibble(state: &mut AdpcmState, nibble: u8) -> Result<i16, AdpcmError> {
    let table_index = state
        .sample_index
        .checked_add(usize::from(nibble))
        .filter(|index| *index < DIFF_TABLE.len())
        .ok_or(AdpcmError::InvalidSampleIndex(state.sample_index))?;

    state.predicted = state.predicted.wrapping_add(DIFF_TABLE[table_index]);
    state.predicted = state.predicted.clamp(i16::MIN as i32, i16::MAX as i32);
    state.sample_index = usize::from(INDEX_TABLE[table_index]);

    Ok(state.predicted as i16)
}

/// Decode a byte slice into interleaved mono signed-16 samples, updating
/// predictor state so multiple blocks can be streamed without discontinuity.
pub fn decode_block(input: &[u8], state: &mut AdpcmState) -> Result<AdpcmBlock, AdpcmError> {
    let mut samples = Vec::with_capacity(input.len().saturating_mul(2));
    for &packed in input {
        samples.push(decode_nibble(state, packed & 0x0F)?);
        samples.push(decode_nibble(state, packed >> 4)?);
    }
    Ok(AdpcmBlock { samples })
}

/// Port of sosCODECInitStream.
pub fn init_stream(state: &mut AdpcmState) {
    *state = AdpcmState::default();
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lookup_tables_match_source_dimensions_and_initial_entries() {
        assert_eq!(DIFF_TABLE.len(), 89 * 16);
        assert_eq!(INDEX_TABLE.len(), 89 * 16);
        assert_eq!(&DIFF_TABLE[..16], &[0, 1, 3, 4, 7, 8, 10, 11, 0, -1, -3, -4, -7, -8, -10, -11]);
        assert_eq!(&INDEX_TABLE[..16], &[0, 0, 0, 0, 32, 64, 96, 128, 0, 0, 0, 0, 32, 64, 96, 128]);
    }

    #[test]
    fn zero_nibbles_preserve_initial_predictor_and_step() {
        let mut state = AdpcmState::default();
        let block = decode_block(&[0x00], &mut state).unwrap();
        assert_eq!(block.samples, [0, 0]);
        assert_eq!(block.decompressed_size_bytes(), 4);
        assert_eq!(state, AdpcmState::default());
    }

    #[test]
    fn low_nibble_is_decoded_before_high_nibble() {
        let mut state = AdpcmState::default();
        let block = decode_block(&[0x11], &mut state).unwrap();
        assert_eq!(block.samples, [1, 2]);
        assert_eq!(state.predicted, 2);
        assert_eq!(state.sample_index, 0);
    }

    #[test]
    fn table_step_changes_between_nibbles() {
        let mut state = AdpcmState::default();
        let block = decode_block(&[0x44], &mut state).unwrap();
        assert_eq!(block.samples, [7, 17]);
        assert_eq!(state.predicted, 17);
        assert_eq!(state.sample_index, 64);
    }

    #[test]
    fn predictor_is_saturated_to_signed_16_bit_range() {
        let mut state = AdpcmState {
            sample_index: 0,
            predicted: 32_760,
        };
        let block = decode_block(&[0x07], &mut state).unwrap();
        assert_eq!(block.samples[0], i16::MAX);
    }

    #[test]
    fn streaming_blocks_match_single_block_decode() {
        let input = [0x17, 0x2A, 0x7F, 0x40, 0x99, 0x08];
        let mut whole_state = AdpcmState::default();
        let whole = decode_block(&input, &mut whole_state).unwrap();

        let mut split_state = AdpcmState::default();
        let mut split_samples = Vec::new();
        for byte in input {
            split_samples.extend(decode_block(&[byte], &mut split_state).unwrap().samples);
        }

        assert_eq!(split_samples, whole.samples);
        assert_eq!(split_state, whole_state);
    }

    #[test]
    fn invalid_external_sample_index_is_reported_not_indexed() {
        let mut state = AdpcmState {
            sample_index: usize::MAX,
            predicted: 0,
        };
        assert_eq!(
            decode_block(&[0], &mut state),
            Err(AdpcmError::InvalidSampleIndex(usize::MAX))
        );
    }
}
